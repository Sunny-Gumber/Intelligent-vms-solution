"""SMTP notifications.

STATUS: implemented, NOT validated against a live SMTP server in this build
environment. The code path is exercised by tests with an injected transport;
real delivery is an external qualification item (docs/verification/).
"""

from __future__ import annotations

import smtplib
import ssl
from dataclasses import dataclass
from email.message import EmailMessage
from typing import Any

from app.config import Settings, get_settings
from app.logging_setup import get_logger

log = get_logger("notifications.email")


@dataclass
class EmailResult:
    ok: bool
    error: str | None = None


def build_message(*, sender: str, recipients: list[str], subject: str, body: str,
                  html: str | None = None) -> EmailMessage:
    message = EmailMessage()
    message["From"] = sender
    message["To"] = ", ".join(recipients)
    message["Subject"] = subject[:200]
    message.set_content(body)
    if html:
        message.add_alternative(html, subtype="html")
    return message


def alarm_subject(alarm: dict[str, Any]) -> str:
    return f"[Intelligent VMS][{str(alarm.get('severity','')).upper()}] " \
           f"{alarm.get('title', 'Alarm')}"


def alarm_body(alarm: dict[str, Any], base_url: str | None = None) -> str:
    lines = [
        f"Alarm:     {alarm.get('title')}",
        f"Severity:  {alarm.get('severity')}",
        f"Camera:    {alarm.get('camera_id') or 'n/a'}",
        f"Occurred:  {alarm.get('occurred_at')}",
        f"Event ID:  {alarm.get('id')}",
    ]
    if base_url and alarm.get("alarm_id"):
        lines.append(f"Open:      {base_url.rstrip('/')}/alarms/{alarm['alarm_id']}")
    lines += ["", "This message was generated by Intelligent VMS."]
    return "\n".join(lines)


class EmailSender:
    def __init__(self, settings: Settings | None = None, transport=None) -> None:  # noqa: ANN001
        self.settings = settings or get_settings()
        self._transport = transport     # injected in tests

    def configured(self) -> bool:
        return bool(self.settings.smtp_host and self.settings.smtp_from)

    def send(self, recipients: list[str], subject: str, body: str,
             html: str | None = None) -> EmailResult:
        if not self.configured():
            return EmailResult(False, "SMTP is not configured on this server")
        if not recipients:
            return EmailResult(False, "no recipients")

        message = build_message(sender=self.settings.smtp_from, recipients=recipients,
                                subject=subject, body=body, html=html)
        if self._transport is not None:
            return self._transport(message)

        try:
            with smtplib.SMTP(self.settings.smtp_host, self.settings.smtp_port,
                              timeout=20) as server:
                if self.settings.smtp_starttls:
                    server.starttls(context=ssl.create_default_context())
                if self.settings.smtp_user:
                    server.login(self.settings.smtp_user,
                                 self.settings.smtp_password or "")
                server.send_message(message)
            log.info("email.sent", recipients=len(recipients), subject=subject[:60])
            return EmailResult(True)
        except (smtplib.SMTPException, OSError, ssl.SSLError) as exc:
            log.error("email.failed", error=str(exc)[:200])
            return EmailResult(False, str(exc)[:300])
